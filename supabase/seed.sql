-- ---------------------------------------------------------------------------
-- URL 共有（009）
--
-- 今月を指す共有を 1 件。これが無いと、画面から 店舗 → アサイン → 発行 と辿るまで
-- `/share/...` を一度も開けない。シフトはアサインすれば即座に公開ページへ出る。
-- ---------------------------------------------------------------------------
-- 「今月」は **JST で** 決める。コンテナのセッション TZ は UTC なので `current_date` を使うと、
-- JST の 0〜9 時に db reset したとき前月を指す共有ができて、画面（todayJst）と 1 か月ずれる
insert into public.shares (id, tenant_id, code, start_date, end_date)
select
  '66666666-6666-6666-6666-000000000001',
  '22222222-2222-2222-2222-222222222222',
  'SEEDSHR1',
  date_trunc('month', jst)::date,
  (date_trunc('month', jst) + interval '1 month' - interval '1 day')::date
from (select (current_timestamp at time zone 'Asia/Tokyo')::date as jst) t;
