const LOGO_WIDTH = 1902

function Squares() {
  return SQUARE_COLORS.map((fill, i) => (
    <rect
      key={i}
      x={(i % 2) * (SQUARE + GAP)}
      y={Math.floor(i / 2) * (SQUARE + GAP)}
      width={SQUARE}
      height={SQUARE}
      rx={RADIUS}
      fill={fill}
    />
  ))
}

type Props = {
  /** 表示の高さ（px）。幅は縦横比から決まる */
  height: number
  className?: string
  style?: CSSProperties
}

/** ロゴ（シンボル + assift）。読み上げは「assift」 */
export function AssiftLogo({ height, className, style }: Props) {
  return (
    <svg
      viewBox={`0 0 ${LOGO_WIDTH} ${SYMBOL_SIZE}`}
      height={height}
      width={(height * LOGO_WIDTH) / SYMBOL_SIZE}
      role="img"
      aria-label="assift"
      className={className}
      style={{ display: 'block', flexShrink: 0, ...style }}
    >
      <Squares />
      <path d={WORDMARK_PATHS.join('')} fill="currentColor" />
    </svg>
  )
}
